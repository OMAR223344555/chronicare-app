    let lang = 'en';
    try { lang = localStorage.getItem('cc-lang') || 'en'; } catch (e) {}

    function t(key, fallback) {
        const d = DICT[lang] || DICT.en;
        return d[key] || DICT.en[key] || fallback || key;
    }

    function applyToDom(root) {
        (root || document).querySelectorAll('[data-i18n]').forEach(el => {
            el.textContent = t(el.getAttribute('data-i18n'));
        });
        (root || document).querySelectorAll('[data-i18n-ph], [data-i18n-placeholder]').forEach(el => {
            el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph') || el.getAttribute('data-i18n-placeholder')));
        });
        (root || document).querySelectorAll('[data-i18n-aria]').forEach(el => {
            el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
        });
        (root || document).querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
        });
        (root || document).querySelectorAll('[data-i18n-aria]').forEach(el => {
            el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
        });
    }

    function applyDir() {
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    }

    function setLang(next) {
        lang = next === 'ar' ? 'ar' : 'en';
        try { localStorage.setItem('cc-lang', lang); } catch (e) {}
        applyDir();
        applyToDom();
        document.querySelectorAll('[data-lang-toggle]').forEach(btn => {
            btn.setAttribute('aria-label', t('lang.switch'));
            btn.textContent = lang === 'ar' ? 'EN' : 'ع';
        });
        document.dispatchEvent(new CustomEvent('cc:lang', { detail: { lang } }));
    }

    document.addEventListener('click', (e) => {
        if (e.target.closest('[data-lang-toggle]')) {
            setLang(lang === 'ar' ? 'en' : 'ar');
        }
    });

    document.addEventListener('DOMContentLoaded', () => {
        applyDir();
        applyToDom();
        document.querySelectorAll('[data-lang-toggle]').forEach(btn => {
            btn.setAttribute('aria-label', t('lang.switch'));
            btn.textContent = lang === 'ar' ? 'EN' : 'ع';
        });
    });

    function fmtDate(iso, opts) {
        const d = new Date(iso + (iso.length === 10 ? 'T00:00:00' : ''));
        const locale = lang === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB';
        return d.toLocaleDateString(locale, opts || { day: '2-digit', month: 'short', year: 'numeric' });
    }

    window.CCi18n = {
        t,
        setLang,
        applyToDom,
        fmtDate,
        get lang() { return lang; },
        get isRTL() { return lang === 'ar'; },
    };
